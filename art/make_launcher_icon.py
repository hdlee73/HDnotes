"""Master drawing -> Android adaptive-icon vectors.
Master: art/hdnotes-icon.svg (same file as web/assets/hdnotes-icon.svg in HDnotes_win).
Writes: app/src/main/res/drawable/ic_launcher_background.xml (the "plate" gradient + "gloss", full bleed)
        app/src/main/res/drawable/ic_launcher_foreground.xml (everything drawn after the gloss, scaled into the 72dp safe area)
Supports rect / path / one level of <g transform="translate(x y) rotate(a)">, fill, stroke, opacity.
Run: python3 art/make_launcher_icon.py"""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = open(os.path.join(root, 'art/hdnotes-icon.svg'), encoding='utf-8').read()
res = os.path.join(root, 'app/src/main/res/drawable')
SCALE, SHIFT_X, SHIFT_Y = 0.7, -3, 0   # foreground: fit the 72dp circle and centre the notebook + pen
col = lambda c: '#FF' + c[1:].upper() if len(c) == 7 else '#FF' + ''.join(ch * 2 for ch in c[1:]).upper()
body = svg.split('fill="url(#gloss)"/>', 1)[1].rsplit('</svg>', 1)[0]
grads = {m[0]: (m[1], m[2]) for m in re.findall(r'<linearGradient id="(\w+)"([^>]*)>(.*?)</linearGradient>', svg, re.S)}
def stops(g): return re.findall(r'stop-color="(#\w+)"(?: stop-opacity="([\d.]+)")?', grads[g][1])
def argb(c, a=None):
    return '#%02X%s' % (round(float(a if a else 1) * 255), col(c)[3:])
def attr(tag, k, d=None):
    m = re.search(r'\s%s="([^"]*)"' % k, tag); return m.group(1) if m else d
def gradient(g, w, h):
    a = grads[g][0]
    x1, y1, x2, y2 = (float(attr(a, k, d)) for k, d in (('x1', 0), ('y1', 0), ('x2', 1), ('y2', 0)))
    items = ''.join(f'\n                <item android:offset="{i}" android:color="{argb(*s)}" />' for i, s in enumerate(stops(g)))
    return f'''
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{x1*w:g}" android:startY="{y1*h:g}" android:endX="{x2*w:g}" android:endY="{y2*h:g}">{items}
            </gradient>
        </aapt:attr>'''
def bg():
    gh = float(re.search(r'<rect width="108" height="([\d.]+)"[^>]*fill="url\(#gloss\)"', svg).group(1))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- HDnotes: blue plate with a soft gloss (art/hdnotes-icon.svg is the master drawing; generated by art/make_launcher_icon.py). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">{gradient('plate', 108, 108)}
    </path>
    <path android:pathData="M0,0h108v{gh:g}h-108z">{gradient('gloss', 108, gh)}
    </path>
</vector>
'''
def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    f = lambda v: ('%.2f' % v).rstrip('0').rstrip('.')
    if r == 0: return f'M{f(x)},{f(y)}h{f(w)}v{f(h)}h-{f(w)}z'
    return (f'M{f(x+r)},{f(y)}h{f(w-2*r)}a{f(r)},{f(r)} 0 0,1 {f(r)},{f(r)}v{f(h-2*r)}a{f(r)},{f(r)} 0 0,1 -{f(r)},{f(r)}'
            f'h-{f(w-2*r)}a{f(r)},{f(r)} 0 0,1 -{f(r)},-{f(r)}v-{f(h-2*r)}a{f(r)},{f(r)} 0 0,1 {f(r)},-{f(r)}z')
def node(tag, ind):
    d = attr(tag, 'd') if tag.startswith('<path') else rrect(*(float(attr(tag, k, 0)) for k in 'x y width height'.split()), float(attr(tag, 'rx', 0)))
    op = attr(tag, 'opacity')
    out = ''
    fill = attr(tag, 'fill')
    if fill and fill != 'none':
        out += f'{ind}<path android:fillColor="{col(fill)}"{f" android:fillAlpha={chr(34)}{float(op):g}{chr(34)}" if op else ""} android:pathData="{d}" />\n'
    if attr(tag, 'stroke'):
        cap = ' android:strokeLineCap="round" android:strokeLineJoin="round"' if attr(tag, 'stroke-linecap') else ''
        out += f'{ind}<path android:strokeColor="{col(attr(tag, "stroke"))}" android:strokeWidth="{attr(tag, "stroke-width")}"{cap} android:pathData="{d}" />\n'
    return out
def fg():
    out = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- HDnotes: notebook with a bookmark and a pen (art/hdnotes-icon.svg is the master drawing; generated by art/make_launcher_icon.py). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <!-- scaled to sit inside the adaptive-icon visible area (72dp circle) -->
    <group android:pivotX="54" android:pivotY="54" android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateX="{SHIFT_X}" android:translateY="{SHIFT_Y}">
'''
    for m in re.finditer(r'<g transform="translate\(([\d.\-]+) ([\d.\-]+)\) rotate\(([\d.\-]+)\)">(.*?)</g>|<(?:path|rect)[^>]*/>', body, re.S):
        if m.group(1) is None:
            out += node(m.group(0), ' ' * 8); continue
        out += f'        <group android:translateX="{m.group(1)}" android:translateY="{m.group(2)}" android:rotation="{m.group(3)}">\n'
        for t in re.findall(r'<(?:path|rect)[^>]*/>', m.group(4)): out += node(t, ' ' * 12)
        out += '        </group>\n'
    return out + '    </group>\n</vector>\n'
open(os.path.join(res, 'ic_launcher_background.xml'), 'w', encoding='utf-8').write(bg())
open(os.path.join(res, 'ic_launcher_foreground.xml'), 'w', encoding='utf-8').write(fg())
print('launcher icon vectors written')
