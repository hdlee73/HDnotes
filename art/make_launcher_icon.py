"""Master drawing -> Android adaptive-icon vectors.
Master: art/hdnotes-icon.svg (same file as web/assets/hdnotes-icon.svg in HDnotes_win).
Writes: app/src/main/res/drawable/ic_launcher_background.xml (mint plate + gloss)
        app/src/main/res/drawable/ic_launcher_foreground.xml (paper stack + pen, scaled into the 72dp safe area)
Run: python3 art/make_launcher_icon.py"""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
svg = open(os.path.join(root, 'art/hdnotes-icon.svg'), encoding='utf-8').read()
res = os.path.join(root, 'app/src/main/res/drawable')
col = lambda c: '#FF' + c[1:].upper() if len(c) == 7 else '#FF' + ''.join(ch * 2 for ch in c[1:]).upper()
body = svg.split('fill="url(#gloss)"/>', 1)[1].rsplit('</svg>', 1)[0]
grads = dict(re.findall(r'<linearGradient id="(\w+)".*?>(.*?)</linearGradient>', svg, re.S))
def stops(g): return re.findall(r'stop-color="(#\w+)"(?: stop-opacity="([\d.]+)")?', grads[g])
def argb(c, a=None):
    h = col(c)[3:]
    return '#%02X%s' % (round(float(a if a is not None else 1) * 255), h)
def bg():
    s0, s1 = stops('plate'); g0, g1 = stops('gloss')
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- HDnotes: mint plate with a soft gloss (art/hdnotes-icon.svg is the master drawing; generated by art/make_launcher_icon.py). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="108">
                <item android:offset="0" android:color="{argb(s0[0])}" />
                <item android:offset="1" android:color="{argb(s1[0])}" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h108v54h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="54">
                <item android:offset="0" android:color="{argb(g0[0], g0[1])}" />
                <item android:offset="1" android:color="{argb(g1[0], g1[1])}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''
def rrect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    f = lambda v: ('%.2f' % v).rstrip('0').rstrip('.')
    if r == 0: return f'M{f(x)},{f(y)}h{f(w)}v{f(h)}h-{f(w)}z'
    return (f'M{f(x+r)},{f(y)}h{f(w-2*r)}a{f(r)},{f(r)} 0 0,1 {f(r)},{f(r)}v{f(h-2*r)}a{f(r)},{f(r)} 0 0,1 -{f(r)},{f(r)}'
            f'h-{f(w-2*r)}a{f(r)},{f(r)} 0 0,1 -{f(r)},-{f(r)}v-{f(h-2*r)}a{f(r)},{f(r)} 0 0,1 {f(r)},-{f(r)}z')
def attr(tag, k, d=None):
    m = re.search(r'\b%s="([^"]*)"' % k, tag); return m.group(1) if m else d
def node(tag, ind):
    d = attr(tag, 'd') if tag.startswith('<path') else rrect(*(float(attr(tag, k)) for k in 'x y width height'.split()), float(attr(tag, 'rx', 0)))
    out = ''
    fill = attr(tag, 'fill')
    if fill: out += f'{ind}<path android:fillColor="{col(fill)}" android:pathData="{d}" />\n'
    if attr(tag, 'stroke'):
        out += (f'{ind}<path android:strokeColor="{col(attr(tag, "stroke"))}" android:strokeWidth="{attr(tag, "stroke-width")}"'
                f'{" android:strokeLineCap=%s" % chr(34) + "round" + chr(34) if attr(tag, "stroke-linecap") else ""}'
                f' android:pathData="{d}" />\n')
        if fill: out = out.replace(f'{ind}<path android:fillColor', f'{ind}<path android:fillColor', 1)
    return out
def fg():
    # sheets and lines (everything before the pen group), then the pen group
    pen = re.search(r'<g transform="translate\(([\d.\-]+) ([\d.\-]+)\) rotate\(([\d.\-]+)\)">(.*?)</g>', body, re.S)
    flat = body[:pen.start()]
    out = '''<?xml version="1.0" encoding="utf-8"?>
<!-- HDnotes: paper stack with a pen (art/hdnotes-icon.svg is the master drawing; generated by art/make_launcher_icon.py). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <!-- scaled to sit inside the adaptive-icon visible area (72dp circle) -->
    <group android:pivotX="54" android:pivotY="54" android:scaleX="0.7" android:scaleY="0.7" android:translateY="-1">
'''
    for t in re.findall(r'<(?:path|rect)[^>]*/>', flat): out += node(t, ' ' * 8)
    out += f'        <group android:translateX="{pen.group(1)}" android:translateY="{pen.group(2)}" android:rotation="{pen.group(3)}">\n'
    for t in re.findall(r'<(?:path|rect)[^>]*/>', pen.group(4)): out += node(t, ' ' * 12)
    out += '        </group>\n    </group>\n</vector>\n'
    return out
open(os.path.join(res, 'ic_launcher_background.xml'), 'w', encoding='utf-8').write(bg())
open(os.path.join(res, 'ic_launcher_foreground.xml'), 'w', encoding='utf-8').write(fg())
print('launcher icon vectors written')
